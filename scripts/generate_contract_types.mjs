/** Generate the two OreFlow consumer boundaries from their canonical JSON Schemas. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'frontend/package.json'));
const { compile } = require('json-schema-to-typescript');
const contracts = [
  ['oreflow-contract-v1', 'OperatingContract'],
  ['oreflow-learning-v2', 'LearningRecord'],
];
const args = process.argv.slice(2);
let check = false;
let outputDir = join(root, 'frontend/src/generated');
let schemaDir = join(root, 'docs/contracts/schemas');
for (let i = 0; i < args.length; i += 1) {
  if (args[i] === '--check') check = true;
  else if (['--output-dir', '--schema-dir'].includes(args[i]) && args[i + 1] && !args[i + 1].startsWith('--')) {
    const flag = args[i];
    const value = resolve(args[++i]);
    if (flag === '--output-dir') outputDir = value;
    else schemaDir = value;
  } else {
    throw new Error(`Unknown or incomplete option: ${args[i]}`);
  }
}
let stale = false;
for (const [id, name] of contracts) {
  const source = (await readFile(join(schemaDir, `${id}.schema.json`), 'utf8')).replaceAll('\r\n', '\n');
  const sha = createHash('sha256').update(source).digest('hex');
  const content = await compile(JSON.parse(source), name, {
    bannerComment: `/* Generated by scripts/generate_contract_types.mjs. Do not edit.\n * Source: docs/contracts/schemas/${id}.schema.json\n * SHA-256 (LF): ${sha}\n */`,
    cwd: schemaDir,
    unknownAny: true,
    // Cardinality is checked at runtime; avoid unions of every allowed array length.
    ignoreMinAndMaxItems: true,
    style: { singleQuote: true, semi: true, printWidth: 120 },
  });
  const path = join(outputDir, `${id}.ts`);
  let previous;
  try { previous = await readFile(path); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const wanted = Buffer.from(content.replaceAll('\r\n', '\n'), 'utf8');
  if (previous?.equals(wanted)) continue;
  if (check) {
    console.error(`Stale or missing generated types: ${path}`);
    stale = true;
  } else {
    await mkdir(outputDir, { recursive: true });
    await writeFile(path, wanted);
    console.log(`Generated ${path}`);
  }
}
if (stale) process.exitCode = 1;
else console.log(`contract types: ${check ? 'fresh' : 'generated'}, ${contracts.length} schemas`);
